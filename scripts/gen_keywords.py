#!/usr/bin/env python3
"""Generate Sql/Keywords.lean from SQLite's own tables (the D7 build):
keyword -> token class (aKWCode, via experiments/kw.c), and the keywords the
grammar lets stand for an identifier (yyFallback ... => ID).
    scripts/gen_keywords.py build/kw.txt build/tk.txt build/fallback.txt"""
import sys
kw, tk, fb = sys.argv[1:4]
codes = {}
for l in open(tk):
    p = l.split()
    if len(p) == 2: codes[int(p[0])] = p[1][3:]
kws = [(l.split()[0], codes[int(l.split()[1])]) for l in open(kw)]
fallback = [l.split()[0] for l in open(fb) if l.split()[1] == 'ID']
out = ['/- GENERATED by scripts/gen_keywords.py from SQLite 3.54.1\'s keyword table',
       '   (aKWCode) and its parser\'s fallback table (yyFallback). Do not edit. -/',
       'namespace Sql', '',
       '/-- SQLite keyword (upper case) and its token class. -/',
       'def keywords : List (String × String) := [']
out.append(',\n'.join(f'  ("{k}", "{c}")' for k, c in kws) + ']')
out += ['', '/-- Token classes that may stand for an identifier (`%fallback ID`). -/',
        'def fallbackToId : List String := [']
out.append(',\n'.join(f'  "{c}"' for c in fallback) + ']')
out += ['', 'end Sql', '']
open('Sql/Keywords.lean', 'w').write('\n'.join(out))
print(len(kws), 'keywords,', len(fallback), 'fallback classes')

#!/usr/bin/env python3
"""Generate Sql/FuncTable.lean: the built-in functions of the D7 build with
their argument counts (-1: any) and kind (s scalar, a aggregate, w window),
from `pragma function_list` of the oracle (build/native/driver-gcc)."""
import subprocess
out = subprocess.run(['build/native/driver-gcc'], input=b"select name, narg, type from pragma_function_list order by name, narg;",
                     capture_output=True, check=True).stdout.decode()
rows = []
for l in out.splitlines():
    n, a, t = l.split('|')
    rows.append((n.strip("'"), int(a), t.strip("'")))
lines = ['/- GENERATED by scripts/gen_functable.py from `pragma function_list` of the',
         '   D7 build of SQLite 3.54.1. Do not edit. -/', 'namespace Sql', '',
         '/-- (name, number of arguments or -1 for any, kind: s scalar, a aggregate, w window) -/',
         'def builtinFunctions : List (String × Int × Char) := [']
lines.append(',\n'.join(f'  ("{n}", {a}, \'{t}\')' for n, a, t in rows) + ']')
lines += ['', 'end Sql', '']
open('Sql/FuncTable.lean', 'w').write('\n'.join(lines))
print(len(rows), 'entries')

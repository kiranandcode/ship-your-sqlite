#!/usr/bin/env python3
"""Generate Sql/PragmaData.lean: the static result sets of PRAGMA
pragma_list, compile_options, collation_list and function_list, read from the
oracle.

The oracle is build/native/driver-ccomp, the native build of the same
c/sqlprog.c by CompCert: the semantics describes the Clight export, and
`PRAGMA compile_options` (and sqlite_compileoption_used/_get) of the ccomp
build differ from the gcc build (ATOMIC_INTRINSICS=0, no COMPILER=gcc-...).
The other lists are identical in both builds (the script checks this).

    scripts/gen_pragma_data.py            # writes Sql/PragmaData.lean
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NATIVE = os.path.join(ROOT, "build", "native")


def run(driver, script):
    out = subprocess.run([os.path.join(NATIVE, driver)], input=script.encode(),
                         stdout=subprocess.PIPE, check=True).stdout.decode()
    return out.splitlines()


def parse_row(line):
    """Split a quote()-style row: 'text' (quotes doubled) or integers, '|'-separated."""
    vals, i = [], 0
    while i < len(line):
        if line[i] == "'":
            j, buf = i + 1, []
            while True:
                if line[j] == "'":
                    if j + 1 < len(line) and line[j + 1] == "'":
                        buf.append("'"); j += 2; continue
                    break
                buf.append(line[j]); j += 1
            vals.append("".join(buf)); i = j + 1
        else:
            j = line.find("|", i)
            j = len(line) if j < 0 else j
            vals.append(int(line[i:j])); i = j
        if i < len(line):
            assert line[i] == "|", line
            i += 1
    return vals


def lean_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rows(driver, script):
    return [parse_row(l) for l in run(driver, script)]


def main():
    oracle = "driver-ccomp"
    pragmas = rows(oracle, "pragma pragma_list;")
    opts = rows(oracle, "pragma compile_options;")
    colls = rows(oracle, "pragma collation_list;")
    funcs = rows(oracle, "pragma function_list;")
    funcs_like = rows(oracle, "pragma case_sensitive_like=0; pragma function_list;")
    for script in ["pragma pragma_list;", "pragma collation_list;", "pragma function_list;",
                   "pragma case_sensitive_like=0; pragma function_list;"]:
        if run("driver-gcc", script) != run(oracle, script):
            sys.exit(f"gcc and ccomp builds differ on {script}")

    def fun_rows(rs):
        return ",\n    ".join(
            f"⟨{lean_str(n)}, {b}, {lean_str(t)}, {lean_str(e)}, {a}, {f}⟩" for n, b, t, e, a, f in rs)

    out = f"""/-
  GENERATED by scripts/gen_pragma_data.py from build/native/driver-ccomp
  (SQLite 3.54.1, the D7 build compiled by CompCert, whose Clight export the
  semantics describes). Do not edit.
-/

namespace Sql.PragmaData

/-- A row of `PRAGMA function_list`. -/
structure FuncRow where
  name : String
  builtin : Int
  type : String
  enc : String
  narg : Int
  flags : Int

/-- `PRAGMA pragma_list` ({len(pragmas)} pragmas, in `aPragmaName` order). -/
def pragmaList : Array String := #[
    {", ".join(lean_str(r[0]) for r in pragmas)}]

/-- `PRAGMA compile_options` of the ccomp build. -/
def compileOptions : Array String := #[
    {", ".join(lean_str(r[0]) for r in opts)}]

/-- `PRAGMA collation_list`. -/
def collationList : Array (Int × String) := #[
    {", ".join(f"({r[0]}, {lean_str(r[1])})" for r in colls)}]

/-- `PRAGMA function_list` of a fresh connection ({len(funcs)} rows, hash order). -/
def functionList : Array FuncRow := #[
    {fun_rows(funcs)}]

/-- `PRAGMA function_list` once `case_sensitive_like` has been set (which
    registers `like` as an application-defined function). -/
def functionListLike : Array FuncRow := #[
    {fun_rows(funcs_like)}]

end Sql.PragmaData
"""
    with open(os.path.join(ROOT, "Sql", "PragmaData.lean"), "w") as fh:
        fh.write(out)
    print(f"Sql/PragmaData.lean: {len(pragmas)} pragmas, {len(opts)} options, "
          f"{len(colls)} collations, {len(funcs)}/{len(funcs_like)} function rows")


if __name__ == "__main__":
    main()

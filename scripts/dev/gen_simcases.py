#!/usr/bin/env python3
"""Phase 2.6g: the simulation of a block function that matches on a
statement, one lemma per constructor (each within the elaboration budget),
then the function by cases. Writes Sql/Den/Sim<MODULE>Manual.lean.

    scripts/dev/gen_simcases.py MODULE FUNCTION INDUCTIVE [--split ctor:field,...]

FUNCTION takes (fuel) (q : QEnv) (s : INDUCTIVE); the constructors of
INDUCTIVE are read from Sql/Ast.lean. --split: constructors whose arms also
match on a field (split on it first)."""
import re, sys
mod, fn, ind = sys.argv[1], sys.argv[2], sys.argv[3]
splits = dict(x.split(':') for x in sys.argv[sys.argv.index('--split') + 1].split(',')) if '--split' in sys.argv else {}
P = mod[0].lower() + mod[1:]
ast = open('Sql/Ast.lean').read()
i = ast.index(f'inductive {ind} where')
j = ast.index('\n\n', i)
body = '\n'.join(l.split('--')[0] for l in ast[i:j].split('\n')[1:])
ctors = []
for part in re.split(r'\n\s*\| ', '\n' + body)[1:]:
    part = ' '.join(part.split())
    name = part.split()[0]
    binders = re.findall(r'\(([^()]*(?:\([^()]*\)[^()]*)*)\)', part[len(name):])
    fields = []
    for b in binders:
        lhs, ty = b.split(':', 1)
        for v in lhs.split():
            v = '«alias»' if v == 'alias' else ('x_' + v if v in ('q', 's') else v)
            fields.append((v, ty.strip()))
    ctors.append((name, fields))
out = [f'''/-
  The simulation of `{fn}` (Phase 2.6g), one lemma per statement kind:
  each within the elaboration budget (the match on the statement reduces to
  one branch). Generated by scripts/dev/gen_simcases.py.
-/
import Sql.Den.Sim{mod}Base

namespace Sql.Den

open Sql
''']
for name, fields in ctors:
    bs = ' '.join(f'({v} : {t})' for v, t in fields)
    args = ' '.join(v for v, _ in fields)
    if name in splits:
        tac = f'  cases {splits[name]} <;> (unfold Sql.{fn} Den.{fn}; sim)\n'
    else:
        tac = f'  unfold Sql.{fn} Den.{fn}\n  sim\n'
    out.append(f'''theorem sim_{fn}_{name} {{ch : Choices}} {{fuel : Nat}} (ih : {mod}Sim ch fuel) (q : QEnv) {bs} :
    Sim ch (Sql.{fn} (fuel + 1) q (.{name} {args})) (Den.{fn} q (.{name} {args})) := by
  {P}_ih ih
''' + tac)
alts = '\n'.join(f'  | {name} {" ".join(v for v, _ in fields)} => exact sim_{fn}_{name} ih q {" ".join(v for v, _ in fields)}'
                 for name, fields in ctors)
out.append(f'''theorem sim_{fn} {{ch : Choices}} {{fuel : Nat}} (ih : {mod}Sim ch fuel) :
    ∀ (q : QEnv) (s : {ind}), Sim ch (Sql.{fn} (fuel + 1) q s) (Den.{fn} q s) := by
  intro q s
  cases s with
{alts}

end Sql.Den
''')
open(f'Sql/Den/Sim{mod}Manual.lean', 'w').write('\n'.join(out))
print(len(ctors), 'constructors')

#!/usr/bin/env python3
"""Phase 2.6g: generate the simulation of an interpreter module's mutual block
by its denotation (as gen_simselect.py does for the query block).

    scripts/dev/gen_simblock.py MODULE FIRST IMPORT [--manual f,g] [--helpers-manual h,i]

MODULE is the interpreter module (Resolve, Exec), FIRST the first function of
its block, IMPORT the module the lemmas build on. Writes
Sql/Den/Sim<MODULE>Base.lean (the lemmas of the monadic helpers before the
block, the structure <MODULE>Sim with one field per block function, fuel 0),
Sim<MODULE>Auto.lean (the block's functions at fuel + 1 by `sim`, but those
--manual, proved in Sim<MODULE>Manual.lean) and Sim<MODULE>All.lean (every
fuel, the lemmas `Sim.f` at every fuel, the helpers after the block)."""
import re, subprocess, sys, os
mod, first, imp = sys.argv[1], sys.argv[2], sys.argv[3]
def opt(name):
    return sys.argv[sys.argv.index(name) + 1].split(',') if name in sys.argv else []
manual, hmanual = opt('--manual'), opt('--helpers-manual')
src = f'Sql/{mod}.lean'
den = open(f'Sql/Den/{mod}.lean').read()
s = open(src).read()
quote = lambda t: re.sub(r'(?<![.\w«])alias(?![\w»])', '«alias»', t)

fields = subprocess.run(['python3', 'scripts/dev/sim_fields.py', src, first],
                        capture_output=True, text=True, check=True).stdout
lines = [quote(l) for l in fields.split('\n') if l.strip() and not l.strip().startswith('--')]
names = [l.split(':')[0].strip() for l in lines]

def header_sig(head):
    """binders and result type of a definition header (after the name)"""
    binders = []; depth = 0; cur = ''; p = 0; res = ''
    while p < len(head):
        c = head[p]
        if c in '([{':
            if depth == 0: cur = ''
            depth += 1
        if depth > 0: cur += c
        if c in ')]}':
            depth -= 1
            if depth == 0: binders.append(cur)
        if depth == 0 and c == ':':
            res = head[p + 1:].strip(); break
        p += 1
    return binders, res

def helper_stmt(name, head):
    binders, res = header_sig(head)
    decls, args = [], []
    fuel = False
    for b in binders:
        if b == '(fuel : Nat)': fuel = True; continue
        br = b[0]; inner = b[1:-1]
        if ':' not in inner:   # {α}: passed by name
            for v in inner.split():
                decls.append('{' + v + ' : Type}'); args.append(f'({v} := {v})')
            continue
        lhs, ty = inner.split(':', 1)
        ty = ty.split(':=')[0].strip()
        for v in lhs.split():
            decls.append(f'{br}{v} : {ty}{")" if br == "(" else "}"}')
            if br == '(': args.append(v)
    a = ' '.join(args)
    lhs = f'Sql.{name} fuel {a}' if fuel else f'Sql.{name} {a}'
    pre = ('(fuel : Nat) ' if fuel else '') + ' '.join(decls)
    body = f'Sim ch ({lhs.strip()}) (Den.{name} {a})'.replace(f'(Den.{name} )', f'Den.{name}')
    return quote(f'∀ {pre}, {body}' if pre.strip() else body)

# the block's extent, and the monadic helpers before and after it
i = s.index(f'def {first} (fuel : Nat)')
bstart = s.rindex('\nmutual\n', 0, i); bend = s.index('\nend\n', i)
def helpers(text):
    out = []
    for m in re.finditer(r'^(?:partial )?def ([\w.]+) ', text, re.M):
        name = m.group(1)
        j = m.end(); depth = 0; k = j
        while True:
            c = text[k]
            if c in '([{': depth += 1
            elif c in ')]}': depth -= 1
            elif text.startswith(':=', k) and depth == 0: break
            k += 1
        head = ' '.join(text[j:k].split())
        if not (re.search(r'\bM\b', head) or '(fuel : Nat)' in head): continue
        if not re.search(rf'^def {re.escape(name)}\b', den, re.M): continue
        out.append((name, helper_stmt(name, head)))
    return out
before, after = helpers(s[:bstart]), helpers(s[bend:])
P = mod[0].lower() + mod[1:]

# the side goals of the oracle's draws: the drawn values are the denotation's
draws = opt('--draws')
DRAW = """
  all_goals
    (try intro _)
    refine ⟨by simp, ?_⟩
    intro c hc
    simp only [List.mem_map, List.mem_range] at hc
    obtain ⟨i, _, rfl⟩ := hc
    omega"""

def helper_lemmas(hs):
    out = []
    for n, st in hs:
        if n in hmanual: continue
        out.append(f'theorem Sim.{n} {{ch : Choices}} :\n    {st} := by\n  intros; unfold Sql.{n} Den.{n}; sim' +
                   (DRAW if n in draws else '') + '\n')
    return out

base = [f'''/-
  The interpreter's {mod} block is simulated by the denotation (Phase 2.6g),
  part 1: the helpers before the block, and the statement for every fuel
  (`{mod}Sim`). Generated by scripts/dev/gen_simblock.py.
-/
import {imp}

namespace Sql.Den

open Sql
'''] + helper_lemmas(before) + [f'''/-- Every function of the interpreter's {mod} block, at `fuel`, is simulated by
    its denotation. -/
structure {mod}Sim (ch : Choices) (fuel : Nat) : Prop where'''] + lines + ['', '/-- At fuel 0 every function of the block runs out of fuel. -/',
    f'theorem {P}Sim_zero (ch : Choices) : {mod}Sim ch 0 where'] + \
    [f'  {n} := by intros; unfold Sql.{n}; exact Sim.outOfFuel _' for n in names] + [f'''
set_option hygiene false in
/-- The fields of an induction hypothesis `{mod}Sim ch fuel`, as hypotheses `h_f`. -/
macro "{P}_ih " ih:ident : tactic =>
  `(tactic| obtain ⟨{", ".join("h_" + x for x in names)}⟩ := $ih)

end Sql.Den
''']
open(f'Sql/Den/Sim{mod}Base.lean', 'w').write('\n'.join(base))

auto = [f'''/-
  The interpreter's {mod} block is simulated by the denotation (Phase 2.6g),
  part 2: the functions `sim` proves, at fuel + 1 from the statement at fuel.
  Generated by scripts/dev/gen_simblock.py.
-/
import Sql.Den.Sim{mod}Base

namespace Sql.Den

open Sql
''']
for l, n in zip(lines, names):
    if n in manual: continue
    stmt = l.split(' : ', 1)[1].replace(f'Sql.{n} fuel', f'Sql.{n} (fuel + 1)')
    auto += [f'theorem sim_{n} {{ch : Choices}} {{fuel : Nat}} (ih : {mod}Sim ch fuel) :\n    {stmt} := by',
             f'  {P}_ih ih', f'  intros; unfold Sql.{n} Den.{n}; sim', '']
auto.append('end Sql.Den')
open(f'Sql/Den/Sim{mod}Auto.lean', 'w').write('\n'.join(auto) + '\n')

imports = [f'import Sql.Den.Sim{mod}Auto'] + ([f'import Sql.Den.Sim{mod}Manual'] if (manual or hmanual) and os.path.exists(f'Sql/Den/Sim{mod}Manual.lean') else [])
allf = [f'''/-
  The interpreter's {mod} block is simulated by the denotation at every fuel
  (Phase 2.6g), and the helpers after it. Generated by scripts/dev/gen_simblock.py.
-/
''' + '\n'.join(imports) + f'''

namespace Sql.Den

open Sql

/-- The {mod} block is simulated at every fuel. -/
theorem {P}Sim (ch : Choices) : ∀ fuel, {mod}Sim ch fuel
  | 0 => {P}Sim_zero ch
  | fuel + 1 =>
    have ih := {P}Sim ch fuel
    {{''']
allf.append(',\n'.join(f'      {n} := sim_{n} ih' for n in names) + ' }')
allf.append('')
for l, n in zip(lines, names):
    stmt = l.split(' : ', 1)[1]
    allf.append(f'theorem Sim.{n} {{ch : Choices}} {{fuel : Nat}} :\n    {stmt} :=\n  ({P}Sim ch fuel).{n}\n')
allf += helper_lemmas(after)
allf.append('end Sql.Den\n')
open(f'Sql/Den/Sim{mod}All.lean', 'w').write('\n'.join(allf))
print(mod, len(names), 'block functions,', len(names) - len([n for n in names if n in manual]), 'by sim;',
      'helpers', [n for n, _ in before], [n for n, _ in after])

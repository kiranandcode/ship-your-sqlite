-- json_group_array / json_group_object (and jsonb_ forms), json_pretty
create table t(g, k, v);
insert into t values (1, 'a', 1), (1, 'b', 'two'), (1, null, 3), (2, 'c', null), (2, 'd', 2.5), (3, null, 1), (3, 'q"x', json('[1,2]'));
select json_group_array(v) from t;
select g, json_group_array(v), json_group_object(k, v) from t group by g;
select json_group_array(k) from t where k is not null;
select json_group_object(k, v) from t;
select json_group_object(k, v) from t where g = 3;
select json_group_object(k, v) from t where k is null;
select json_group_array(v) from t where 0;
select json_group_object(k, v) from t where 0;
select jsonb_group_array(v) from t where 0;
select jsonb_group_object(k, v) from t where 0;
select g, jsonb_group_array(v), jsonb_group_object(k, v) from t group by g;
select json_group_array(json('{"a":1}')) from t;
select json_group_array(json_array(g, v)) from t;
select json_group_object(k, json_object('v', v)) from t where k is not null;
select json_group_array(jsonb('[1]')) from t where g = 1;
select json_group_array(1.5), json_group_array(1e300*1e300), json_group_object('x', 0.1+0.2) from t where g = 2;
select json_group_object(g, k) from t;
select json_group_object(x, x) from (select 'a' as x union all select null union all select 'b' union all select null);
select json_group_object(x, 1) from (select null as x union all select null);
select json_group_object(x, '@,"') from (select 'a@' as x union all select null union all select 'c');
select json_group_array(distinct g) from t;
select json_group_array(v) filter (where g = 1) from t;
select count(*), json_group_array(k) from t group by g having count(*) > 1;
select json_group_array(v order by v desc) from t where g = 1;
select json_pretty('{"a":[1,2,{"b":null,"c":[]}],"d":{}}');
select json_pretty('{"a":[1,2,{"b":null,"c":[]}],"d":{}}', '  '), json_pretty('[1,[2,[3]]]', ''), json_pretty('[1]', null);
select json_pretty('"x"'), json_pretty('5'), json_pretty('[]'), json_pretty('{}'), json_pretty(null), json_pretty('{a:0x10,b:[.5]}');
select json_pretty(jsonb('{"k":["v",{"w":1}]}'), char(9));
select json_pretty('[1]', 1), json_pretty('{"a":"x"}', 'ab');

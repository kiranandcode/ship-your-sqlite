-- result-set pragmas on a schema with indexes, foreign keys, WITHOUT ROWID,
-- generated columns, defaults, collations and views
create table p(id integer primary key, code text unique collate nocase, x real default 1.5, y default -3, z default (1+2), w default 'it''s', v default CURRENT_TIMESTAMP, u default +7);
create table c(a int not null, b text references p(code) on delete cascade on update set null, c2 int, d int default null,
  primary key(a desc, c2), unique(b, c2), unique(c2 collate nocase), foreign key(c2, d) references p(id, code) on delete restrict);
create table w(k integer primary key, v text unique, s int unique on conflict replace) without rowid;
create table g(a int, b int generated always as (a*2) virtual, c int as (a+1) stored, d text);
create table r(a, b, c, unique(a) on conflict replace, unique(b), unique(a, b), unique(a));
create index pi on p(x desc, y collate nocase);
create unique index pj on p(lower(code), z) where x > 0;
create index ci on c(d);
create index wi on w(s);
create index gi on g(b, d);
create view v1 as select id, code as cc, x+1, y from p;
create view v2(q, r) as select 1, 'a';
